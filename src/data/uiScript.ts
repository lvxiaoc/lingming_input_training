export function toSimplifiedUi(text: string): string {
  if (!text) return text;
  let out = text;
  for (const [trad, simp] of PHRASE_REPLACEMENTS) {
    if (out.includes(trad)) {
      out = out.split(trad).join(simp);
    }
  }
  let converted = '';
  let changed = false;
  for (let i = 0; i < out.length; i++) {
    const ch = out[i];
    const rep = CHAR_MAP[ch];
    if (rep) {
      converted += rep;
      changed = true;
    } else {
      converted += ch;
    }
  }
  return changed ? converted : out;
}

export function uiText(text: string, uiScript: UiScript): string {
  if (uiScript === 'trad' || !text) return text;
  return toSimplifiedUi(text);
}

/**
 * Converts structural prose inside a palace mnemonic without mutating literal radical glyphs
 * (e.g. 鳥烏魚 / 業馬言病虎 / 內外缶骨丑車).
 */
export function uiMnemonic(text: string, uiScript: UiScript): string {
  if (uiScript === 'trad' || !text) return text;
  let out = text;
  for (const [trad, simp] of MNEMONIC_PROSE_TOKENS) {
    if (out.includes(trad)) {
      out = out.split(trad).join(simp);
    }
  }
  return out;
}

export const UiScriptContext = createContext<UiScript>('trad');

export function useUiScript(): UiScript {
  return useContext(UiScriptContext);
}

export function useUiText(): (text: string) => string {
  const uiScript = useContext(UiScriptContext);
  return (text: string) => uiText(text, uiScript);
}
